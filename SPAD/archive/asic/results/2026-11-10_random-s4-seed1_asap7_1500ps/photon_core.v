module photon_core(input clk, input rst, input valid, input [9:0] arrival,
                   output reg [9:0] candidate);
  reg [3:0] confidence;
  reg [3:0] state;
  wire [10:0] above = arrival - candidate;
  wire [10:0] below = candidate - arrival;
  wire gt = arrival > candidate;
  wire lt = arrival < candidate;
  wire [10:0] size = gt ? above : below;
  wire near1 = size <= 1;
  wire near2 = size <= 2;
  wire near4 = size <= 4;
  wire near8 = size <= 8;
  wire near16 = size <= 16;
  wire zero = confidence == 0;
  wire conf2 = confidence >= 2;
  wire conf4 = confidence >= 4;
  wire conf8 = confidence >= 8;
  wire full = confidence == 15;
  wire const0 = 1'b0;
  wire const1 = 1'b1;
  wire state0 = state[0];
  wire state1 = state[1];
  wire state2 = state[2];
  wire state3 = state[3];
  wire g0_0 = (~state2 & ~gt) | (state2 & ~gt);
  wire g0_1 = (~conf2 & ~state2) | (conf2 & ~state2);
  wire g0_2 = 1'b0;
  wire g0_3 = (zero & ~state0);
  wire g0_4 = (~near1 & ~conf4) | (near1 & ~conf4);
  wire g0_5 = (gt & ~gt) | (gt & gt);
  wire g0_6 = (~conf2 & lt) | (conf2 & lt);
  wire g0_7 = 1'b0;
  wire g0_8 = (gt & ~gt) | (gt & gt);
  wire g0_9 = 1'b0;
  wire g0_10 = (gt & ~lt) | (gt & lt);
  wire g0_11 = (~zero & ~state2) | (~zero & state2) | (zero & ~state2) | (zero & state2);
  wire g0_12 = (~const0 & ~full) | (const0 & ~full);
  wire g0_13 = 1'b0;
  wire g0_14 = (~state3 & ~near2) | (~state3 & near2) | (state3 & ~near2) | (state3 & near2);
  wire g0_15 = 1'b0;
  wire g1_0 = 1'b0;
  wire g1_1 = (~conf4 & ~state3) | (~conf4 & state3);
  wire g1_2 = (~g0_13 & lt) | (g0_13 & lt);
  wire g1_3 = (~g0_8 & g0_11) | (g0_8 & g0_11);
  wire g1_4 = (~g0_8 & state1) | (g0_8 & state1);
  wire g1_5 = 1'b0;
  wire g1_6 = (~g0_11 & ~g0_7) | (~g0_11 & g0_7) | (g0_11 & ~g0_7) | (g0_11 & g0_7);
  wire g1_7 = (~lt & near4) | (lt & ~near4);
  wire g1_8 = (~near4 & ~const1) | (~near4 & const1) | (near4 & ~const1) | (near4 & const1);
  wire g1_9 = (~near4 & ~conf8) | (~near4 & conf8);
  wire g1_10 = (~g0_7 & full) | (g0_7 & full);
  wire g1_11 = (near16 & ~near1) | (near16 & near1);
  wire g1_12 = (~g0_2 & ~state0) | (g0_2 & ~state0);
  wire g1_13 = (g0_7 & ~state3) | (g0_7 & state3);
  wire g1_14 = 1'b0;
  wire g1_15 = (~full & ~g0_3) | (full & ~g0_3);
  wire g2_0 = (~g1_6 & g1_11) | (g1_6 & g1_11);
  wire g2_1 = (g1_11 & ~lt) | (g1_11 & lt);
  wire g2_2 = 1'b0;
  wire g2_3 = (~state1 & ~conf4) | (~state1 & conf4);
  wire g2_4 = (g1_9 & ~g1_15);
  wire g2_5 = (~lt & g1_11) | (lt & ~g1_11);
  wire g2_6 = (~conf4 & g1_7) | (conf4 & g1_7);
  wire g2_7 = (g1_4 & near8);
  wire g2_8 = (g1_0 & ~state3) | (g1_0 & state3);
  wire g2_9 = (~g1_4 & g1_15) | (g1_4 & g1_15);
  wire g2_10 = (~near2 & const0) | (near2 & const0);
  wire g2_11 = 1'b0;
  wire g2_12 = (conf2 & ~const0) | (conf2 & const0);
  wire g2_13 = (~near1 & state3) | (near1 & state3);
  wire g2_14 = (~g1_0 & g1_9) | (g1_0 & g1_9);
  wire g2_15 = 1'b0;
  wire do_replace = g2_4;
  wire do_up = g2_5;
  wire do_down = g2_6;
  wire do_inc = g2_7;
  wire do_dec = g2_8;
  wire [9:0] raised = (do_up && !do_down && candidate != 1023) ? candidate + 1'b1 : candidate;
  wire [9:0] stepped = (do_down && !do_up && candidate != 0) ? candidate - 1'b1 : raised;
  always @(posedge clk) begin
    if (rst) begin
      candidate <= 0;
      confidence <= 0;
      state <= 0;
    end else if (valid) begin
      candidate <= do_replace ? arrival : stepped;
      if (do_inc && !do_dec && confidence != 15) confidence <= confidence + 1'b1;
      if (do_dec && !do_inc && confidence != 0) confidence <= confidence - 1'b1;
      state[0] <= g2_0;
      state[1] <= g2_1;
      state[2] <= g2_2;
      state[3] <= g2_3;
    end
  end
endmodule
