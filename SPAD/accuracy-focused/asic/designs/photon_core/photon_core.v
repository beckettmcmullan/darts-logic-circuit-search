module photon_core(input clk, input rst, input valid, input [9:0] arrival,
                   output reg [12:0] candidate);
  reg [4:0] confidence;
  reg [7:0] state;
  wire [12:0] arrival_fx = {arrival, 3'b0};
  wire [13:0] above = arrival_fx - candidate;
  wire [13:0] below = candidate - arrival_fx;
  wire gt = arrival_fx > candidate;
  wire lt = arrival_fx < candidate;
  wire [13:0] size = gt ? above : below;
  wire near1 = size <= 8;
  wire near2 = size <= 16;
  wire near4 = size <= 32;
  wire near8 = size <= 64;
  wire near16 = size <= 128;
  wire zero = confidence == 0;
  wire conf2 = confidence >= 2;
  wire conf4 = confidence >= 4;
  wire conf8 = confidence >= 8;
  wire conf16 = confidence >= 16;
  wire full = confidence == 31;
  wire const0 = 1'b0;
  wire const1 = 1'b1;
  reg [9:0] cfifo0;
  reg [9:0] cfifo1;
  reg [9:0] cfifo2;
  reg [9:0] cfifo3;
  reg cvalid0;
  reg cvalid1;
  reg cvalid2;
  reg cvalid3;
  reg acquired;
  wire [10:0] cdiff0 = {1'b0, arrival} - {1'b0, cfifo0} + 11'd8;
  wire [10:0] cdiff1 = {1'b0, arrival} - {1'b0, cfifo1} + 11'd8;
  wire [10:0] cdiff2 = {1'b0, arrival} - {1'b0, cfifo2} + 11'd8;
  wire [10:0] cdiff3 = {1'b0, arrival} - {1'b0, cfifo3} + 11'd8;
  wire coinc = (cvalid0 && cdiff0 <= 16) | (cvalid1 && cdiff1 <= 16) | (cvalid2 && cdiff2 <= 16) | (cvalid3 && cdiff3 <= 16);
  wire state0 = state[0];
  wire state1 = state[1];
  wire state2 = state[2];
  wire state3 = state[3];
  wire state4 = state[4];
  wire state5 = state[5];
  wire state6 = state[6];
  wire state7 = state[7];
  wire g0_0 = (~state4 & ~full) | (~state4 & full) | (state4 & full);
  wire g0_1 = (~const0 & ~const0) | (~const0 & const0);
  wire g0_2 = (~const0 & ~const0) | (const0 & ~const0) | (const0 & const0);
  wire g0_3 = (~const0 & ~const0) | (~const0 & const0);
  wire g0_4 = 1'b0;
  wire g0_5 = 1'b0;
  wire g0_6 = 1'b0;
  wire g0_7 = (~const0 & ~near2) | (~const0 & near2) | (const0 & near2);
  wire g0_8 = (~const0 & ~const0) | (~const0 & const0) | (const0 & const0);
  wire g0_9 = (~const0 & ~const0) | (~const0 & const0);
  wire g0_10 = (~near16 & ~near1) | (near16 & ~near1) | (near16 & near1);
  wire g0_11 = (~const0 & ~const0) | (~const0 & const0) | (const0 & const0);
  wire g0_12 = (~const0 & ~const0);
  wire g0_13 = (~state2 & const0) | (state2 & const0);
  wire g0_14 = (~const0 & const0) | (const0 & ~const0);
  wire g0_15 = (~conf4 & const0) | (conf4 & ~const0);
  wire g0_16 = (~const0 & const0) | (const0 & ~const0);
  wire g0_17 = (~const0 & const0) | (const0 & const0);
  wire g0_18 = (const0 & ~const0);
  wire g0_19 = (~const0 & ~const0);
  wire g0_20 = (~const0 & const0);
  wire g0_21 = (~const0 & ~const0) | (const0 & ~const0) | (const0 & const0);
  wire g0_22 = (~near2 & ~near2) | (near2 & near2);
  wire g0_23 = (const0 & ~const0);
  wire g0_24 = (~const0 & ~const0) | (~const0 & const0) | (const0 & ~const0) | (const0 & const0);
  wire g0_25 = (~const0 & ~const0);
  wire g0_26 = (const0 & const0);
  wire g0_27 = (~state3 & ~const0) | (~state3 & const0);
  wire g0_28 = (const0 & ~const1);
  wire g0_29 = (~const0 & ~const0) | (~const0 & const0) | (const0 & ~const0);
  wire g0_30 = (~const0 & ~const0) | (const0 & ~const0) | (const0 & const0);
  wire g0_31 = (~const0 & ~state7) | (~const0 & state7) | (const0 & state7);
  wire g0_32 = 1'b0;
  wire g0_33 = 1'b0;
  wire g0_34 = 1'b0;
  wire g0_35 = 1'b0;
  wire g0_36 = 1'b0;
  wire g0_37 = 1'b0;
  wire g0_38 = 1'b0;
  wire g0_39 = 1'b0;
  wire g1_0 = (~conf8 & ~g0_16) | (conf8 & ~g0_16) | (conf8 & g0_16);
  wire g1_1 = 1'b0;
  wire g1_2 = 1'b0;
  wire g1_3 = (~const0 & const0) | (const0 & ~const0) | (const0 & const0);
  wire g1_4 = (~g0_26 & ~const0) | (g0_26 & ~const0) | (g0_26 & const0);
  wire g1_5 = (~const0 & const0) | (const0 & const0);
  wire g1_6 = (~lt & near16);
  wire g1_7 = (~const0 & const0) | (const0 & const0);
  wire g1_8 = (~g0_17 & const0) | (g0_17 & ~const0);
  wire g1_9 = (~const0 & ~const0) | (~const0 & const0) | (const0 & const0);
  wire g1_10 = (const0 & ~const0) | (const0 & const0);
  wire g1_11 = (~const0 & ~g0_27) | (~const0 & g0_27);
  wire g1_12 = (const0 & const0);
  wire g1_13 = (~const0 & const0) | (const0 & ~const0);
  wire g1_14 = (~const0 & g0_27) | (const0 & ~g0_27) | (const0 & g0_27);
  wire g1_15 = (~const0 & ~g0_11) | (~const0 & g0_11) | (const0 & ~g0_11);
  wire g1_16 = (~conf16 & ~g0_22) | (conf16 & g0_22);
  wire g1_17 = (const0 & ~g0_20) | (const0 & g0_20);
  wire g1_18 = 1'b0;
  wire g1_19 = 1'b0;
  wire g1_20 = (const0 & ~const0);
  wire g1_21 = (~g0_21 & ~const0);
  wire g1_22 = (~zero & ~g0_3) | (~zero & g0_3);
  wire g1_23 = (~const0 & const0);
  wire g1_24 = (~gt & const0) | (gt & ~const0) | (gt & const0);
  wire g1_25 = (~const0 & const0);
  wire g1_26 = (const0 & ~near1);
  wire g1_27 = (const0 & const0);
  wire g1_28 = (~g0_23 & ~g0_0) | (g0_23 & ~g0_0);
  wire g1_29 = (const0 & ~const0) | (const0 & const0);
  wire g1_30 = (~state4 & conf8) | (state4 & ~conf8);
  wire g1_31 = (~g0_25 & const0) | (g0_25 & ~const0) | (g0_25 & const0);
  wire g1_32 = 1'b0;
  wire g1_33 = 1'b0;
  wire g1_34 = 1'b0;
  wire g1_35 = 1'b0;
  wire g1_36 = 1'b0;
  wire g1_37 = 1'b0;
  wire g1_38 = 1'b0;
  wire g1_39 = 1'b0;
  wire g2_0 = (~state0 & ~const0) | (~state0 & const0) | (state0 & const0);
  wire g2_1 = (~near16 & ~g1_28) | (near16 & ~g1_28) | (near16 & g1_28);
  wire g2_2 = 1'b0;
  wire g2_3 = (~zero & near8) | (zero & near8);
  wire g2_4 = (~state4 & ~state3);
  wire g2_5 = (~state5 & const0) | (state5 & ~const0) | (state5 & const0);
  wire g2_6 = (~zero & ~const0) | (zero & const0);
  wire g2_7 = (~g1_21 & ~const0) | (g1_21 & const0);
  wire g2_8 = (~g1_6 & zero);
  wire g2_9 = (~g1_6 & ~g1_22) | (g1_6 & g1_22);
  wire g2_10 = (~near8 & ~state7) | (near8 & state7);
  wire g2_11 = (~near8 & state1) | (near8 & ~state1) | (near8 & state1);
  wire g2_12 = (~near8 & ~state3);
  wire g2_13 = (~g1_6 & near1) | (g1_6 & ~near1);
  wire g2_14 = (full & ~g1_24) | (full & g1_24);
  wire g2_15 = 1'b0;
  wire g2_16 = (const0 & ~const0);
  wire g2_17 = (g1_20 & ~const0) | (g1_20 & const0);
  wire g2_18 = (~const0 & const0);
  wire g2_19 = (~const0 & const0) | (const0 & const0);
  wire g2_20 = (const0 & ~const0);
  wire g2_21 = (~const0 & ~const0) | (const0 & const0);
  wire g2_22 = (~g1_8 & ~const0) | (g1_8 & const0);
  wire g2_23 = (const0 & ~const0) | (const0 & const0);
  wire g2_24 = (~const0 & const0) | (const0 & ~const0);
  wire g2_25 = (~const0 & state5);
  wire g2_26 = (~const0 & const0);
  wire g2_27 = (~const0 & const0);
  wire g2_28 = (~const0 & gt);
  wire g2_29 = (~g1_7 & ~const0) | (~g1_7 & const0) | (g1_7 & ~const0) | (g1_7 & const0);
  wire g2_30 = (~const0 & ~g1_17) | (~const0 & g1_17);
  wire g2_31 = (~const0 & ~const0) | (~const0 & const0) | (const0 & ~const0);
  wire g2_32 = 1'b0;
  wire g2_33 = 1'b0;
  wire g2_34 = 1'b0;
  wire g2_35 = 1'b0;
  wire g2_36 = 1'b0;
  wire g2_37 = 1'b0;
  wire g2_38 = 1'b0;
  wire g2_39 = 1'b0;
  wire blocked = g2_8 & acquired & ~near16 & ~coinc;
  wire do_replace = g2_8 & ~blocked;
  wire do_up = g2_9 & ~blocked;
  wire do_down = g2_10 & ~blocked;
  wire do_inc = g2_11;
  wire do_dec = g2_12;
  wire [12:0] step = 13'd8 >> {g2_14, g2_13};
  wire [13:0] sum = {1'b0, candidate} + {1'b0, step};
  wire [12:0] raised = (do_up && !do_down) ? (sum[13] ? 13'd8191 : sum[12:0]) : candidate;
  wire [12:0] stepped = (do_down && !do_up) ? (candidate < step ? 13'd0 : candidate - step) : raised;
  always @(posedge clk) begin
    if (rst) begin
      candidate <= 0;
      confidence <= 0;
      state <= 0;
      cfifo0 <= 0;
      cfifo1 <= 0;
      cfifo2 <= 0;
      cfifo3 <= 0;
      cvalid0 <= 0;
      cvalid1 <= 0;
      cvalid2 <= 0;
      cvalid3 <= 0;
      acquired <= 0;
    end else if (valid) begin
      candidate <= do_replace ? arrival_fx : stepped;
      if (do_inc && !do_dec && confidence != 31) confidence <= confidence + 1'b1;
      if (do_dec && !do_inc && confidence != 0) confidence <= confidence - 1'b1;
      state[0] <= g2_0;
      state[1] <= g2_1;
      state[2] <= g2_2;
      state[3] <= g2_3;
      state[4] <= g2_4;
      state[5] <= g2_5;
      state[6] <= g2_6;
      state[7] <= g2_7;
      cfifo0 <= arrival;
      cvalid0 <= 1'b1;
      cfifo1 <= cfifo0;
      cfifo2 <= cfifo1;
      cfifo3 <= cfifo2;
      cvalid1 <= cvalid0;
      cvalid2 <= cvalid1;
      cvalid3 <= cvalid2;
      if (do_replace) acquired <= 1'b1;
    end
  end
endmodule
