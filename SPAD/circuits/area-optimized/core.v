module photon_core(input clk, input rst, input valid, input [9:0] arrival,
                   output reg [9:0] candidate);
  reg [3:0] confidence;
  reg [3:0] state;
  wire [10:0] above = arrival - candidate;
  wire [10:0] below = candidate - arrival;
  wire gt = arrival > candidate;
  wire lt = arrival < candidate;
  wire [10:0] size = gt ? above : below;
  wire near1 = size <= 1;
  wire near2 = size <= 2;
  wire near4 = size <= 4;
  wire near8 = size <= 8;
  wire near16 = size <= 16;
  wire zero = confidence == 0;
  wire conf2 = confidence >= 2;
  wire conf4 = confidence >= 4;
  wire conf8 = confidence >= 8;
  wire full = confidence == 15;
  wire const0 = 1'b0;
  wire const1 = 1'b1;
  wire state0 = state[0];
  wire state1 = state[1];
  wire state2 = state[2];
  wire state3 = state[3];
  wire g0_0 = (~near1 & ~conf2) | (near1 & ~conf2);
  wire g0_1 = (~near2 & ~conf2) | (~near2 & conf2) | (near2 & ~conf2) | (near2 & conf2);
  wire g0_2 = (~const1 & ~conf8) | (~const1 & conf8);
  wire g0_3 = (~gt & conf8) | (gt & conf8);
  wire g0_4 = (near8 & ~full) | (near8 & full);
  wire g0_5 = (~conf8 & ~state2) | (~conf8 & state2) | (conf8 & ~state2) | (conf8 & state2);
  wire g0_6 = (~near4 & ~gt) | (~near4 & gt) | (near4 & ~gt) | (near4 & gt);
  wire g0_7 = (~conf8 & ~lt) | (~conf8 & lt) | (conf8 & ~lt) | (conf8 & lt);
  wire g0_8 = (~near4 & ~lt);
  wire g0_9 = (~state0 & ~state3) | (state0 & state3);
  wire g0_10 = (lt & state1);
  wire g0_11 = (~const1 & ~state0);
  wire g0_12 = (~state0 & near4) | (state0 & ~near4) | (state0 & near4);
  wire g0_13 = (~state1 & near4) | (state1 & near4);
  wire g0_14 = (~conf4 & ~state2) | (conf4 & ~state2) | (conf4 & state2);
  wire g0_15 = (gt & ~state0) | (gt & state0);
  wire g1_0 = (~g0_0 & ~state1) | (g0_0 & ~state1) | (g0_0 & state1);
  wire g1_1 = 1'b0;
  wire g1_2 = (~g0_9 & ~g0_3) | (~g0_9 & g0_3) | (g0_9 & g0_3);
  wire g1_3 = (~g0_7 & state0) | (g0_7 & ~state0) | (g0_7 & state0);
  wire g1_4 = 1'b0;
  wire g1_5 = (const1 & ~lt) | (const1 & lt);
  wire g1_6 = 1'b0;
  wire g1_7 = (~near2 & ~gt) | (~near2 & gt) | (near2 & gt);
  wire g1_8 = (g0_6 & ~g0_13) | (g0_6 & g0_13);
  wire g1_9 = (~g0_5 & near16) | (g0_5 & near16);
  wire g1_10 = (~state3 & ~g0_10);
  wire g1_11 = (~g0_12 & g0_15);
  wire g1_12 = (g0_6 & g0_1);
  wire g1_13 = (g0_1 & ~state3);
  wire g1_14 = (~g0_5 & ~g0_15) | (~g0_5 & g0_15) | (g0_5 & ~g0_15) | (g0_5 & g0_15);
  wire g1_15 = (~near16 & ~g0_8) | (near16 & g0_8);
  wire g2_0 = (~conf4 & g1_11) | (conf4 & ~g1_11);
  wire g2_1 = (state2 & ~near16);
  wire g2_2 = (~g1_9 & ~zero) | (~g1_9 & zero) | (g1_9 & zero);
  wire g2_3 = (g1_14 & ~lt);
  wire g2_4 = (~conf2 & ~conf8) | (~conf2 & conf8);
  wire g2_5 = (~g1_13 & ~g1_15) | (~g1_13 & g1_15) | (g1_13 & g1_15);
  wire g2_6 = (~g1_15 & ~near16) | (~g1_15 & near16) | (g1_15 & ~near16);
  wire g2_7 = (~g1_3 & ~g1_0) | (g1_3 & g1_0);
  wire g2_8 = (~g1_9 & state1);
  wire g2_9 = (~near4 & ~g1_3) | (~near4 & g1_3);
  wire g2_10 = (~g1_3 & g1_4) | (g1_3 & g1_4);
  wire g2_11 = (~g1_7 & ~g1_3) | (g1_7 & g1_3);
  wire g2_12 = (~state1 & ~g1_12) | (state1 & ~g1_12) | (state1 & g1_12);
  wire g2_13 = (~conf2 & g1_10) | (conf2 & ~g1_10) | (conf2 & g1_10);
  wire g2_14 = (~conf8 & ~const0);
  wire g2_15 = (~g1_12 & near16) | (g1_12 & near16);
  wire do_replace = g2_4;
  wire do_up = g2_5;
  wire do_down = g2_6;
  wire do_inc = g2_7;
  wire do_dec = g2_8;
  wire [9:0] raised = (do_up && !do_down && candidate != 1023) ? candidate + 1'b1 : candidate;
  wire [9:0] stepped = (do_down && !do_up && candidate != 0) ? candidate - 1'b1 : raised;
  always @(posedge clk) begin
    if (rst) begin
      candidate <= 0;
      confidence <= 0;
      state <= 0;
    end else if (valid) begin
      candidate <= do_replace ? arrival : stepped;
      if (do_inc && !do_dec && confidence != 15) confidence <= confidence + 1'b1;
      if (do_dec && !do_inc && confidence != 0) confidence <= confidence - 1'b1;
      state[0] <= g2_0;
      state[1] <= g2_1;
      state[2] <= g2_2;
      state[3] <= g2_3;
    end
  end
endmodule
